def table(name: str) -> dict | None:
    """按表名取表。"""
    return LIFEPATH.get(name)


def roll(rng: random.Random, name: str) -> dict | None:
    """投 1d10 查表，返回 {"table","roll","text","columns"}（表不存在返回 None）。"""
    t = LIFEPATH.get(name)
    if not t:
        return None
    face = rng.randint(1, 10)
    row = t["entries"].get(str(face)) or t["entries"].get(face)
    if row is None:  # 表用区间而不是单点（例如数量表）
        row = next(iter(t["entries"].values()), [""])
    return {"table": name, "roll": face, "columns": t.get("columns"),
            "text": list(row)}


