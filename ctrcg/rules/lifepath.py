def roll_all(rng: random.Random) -> dict:
    """把整条人生之路走完，返回 {表名: {"roll","text"}}。"""
    out: dict = {}
    for name in ROLL_ORDER:
        r = roll(rng, name)
        if r:
            out[name] = {"roll": r["roll"], "text": r["text"]}
    return out
